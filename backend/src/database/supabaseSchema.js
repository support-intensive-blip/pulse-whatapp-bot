const logger = require('../utils/logger');
const { listSyncTables } = require('./supabaseSync');

/**
 * Builds the Postgres mirror of the live SQLite schema, and (with SUPABASE_DB_URL)
 * applies it on boot so Supabase always has every table/column before syncing.
 * Idempotent: IF NOT EXISTS everywhere.
 */

function q(name) {
  return `"${String(name).replace(/"/g, '""')}"`;
}

function postgresType(sqliteType) {
  const t = String(sqliteType || '').toUpperCase();
  if (t.includes('INT')) return 'bigint';
  if (t.includes('REAL') || t.includes('FLOA') || t.includes('DOUB')) return 'double precision';
  return 'text';
}

function tableSql(db, table, pk) {
  const columns = db.prepare(`PRAGMA table_info(${q(table)})`).all();
  const pkCol = columns.find((c) => c.name === pk);
  const lines = [];

  lines.push(`-- ${table}`);
  lines.push(
    `CREATE TABLE IF NOT EXISTS public.${q(table)} (${q(pk)} ${postgresType(pkCol.type)} PRIMARY KEY);`
  );
  for (const col of columns) {
    if (col.name === pk) continue;
    lines.push(
      `ALTER TABLE public.${q(table)} ADD COLUMN IF NOT EXISTS ${q(col.name)} ${postgresType(col.type)};`
    );
  }

  // Same lookups as SQLite, but never UNIQUE: rows arrive asynchronously and SQLite
  // already enforces uniqueness, so a transient overlap must not reject a sync.
  for (const index of db.prepare(`PRAGMA index_list(${q(table)})`).all()) {
    if (index.origin === 'pk') continue;
    const cols = db
      .prepare(`PRAGMA index_info(${q(index.name)})`)
      .all()
      .map((c) => c.name)
      .filter(Boolean);
    if (!cols.length) continue;
    const name = index.name.startsWith('sqlite_autoindex_')
      ? `idx_${table}_${cols.join('_')}`
      : index.name;
    lines.push(
      `CREATE INDEX IF NOT EXISTS ${q(name)} ON public.${q(table)} (${cols.map(q).join(', ')});`
    );
  }

  // RLS on with no policies: only the server's secret key can read or write.
  lines.push(`ALTER TABLE public.${q(table)} ENABLE ROW LEVEL SECURITY;`);
  return lines.join('\n');
}

function buildSupabaseSchemaSql(db) {
  const tables = listSyncTables(db);
  const header = `-- Pulse: Supabase (Postgres) schema, mirrored from the SQLite schema.
-- GENERATED by \`npm run supabase:schema\` (src/database/supabaseSchema.js). Do not edit by hand.
-- The server applies this itself on boot when SUPABASE_DB_URL is set.
--
-- Safe to re-run: run the whole file in the Supabase SQL editor after every regenerate.
-- Types follow SQLite exactly (INTEGER -> bigint, REAL -> double precision, TEXT -> text;
-- timestamps stay text in SQLite's format) so rows round-trip unchanged.
-- Only primary keys are declared: SQLite enforces NOT NULL / UNIQUE / foreign keys before
-- a row is synced. Every table has RLS on with no policies, so the publishable (anon) key
-- sees nothing; the backend uses SUPABASE_SECRET_KEY.
`;
  const body = tables.map(({ table, pk }) => tableSql(db, table, pk)).join('\n\n');
  const footer = `\n\n-- Make PostgREST pick up new tables/columns immediately.\nNOTIFY pgrst, 'reload schema';\n`;
  return { sql: `${header}\n${body}${footer}`, tableCount: tables.length };
}

/** Creates/extends the Supabase tables over a direct Postgres connection. */
async function applySupabaseSchema(db) {
  const connectionString = process.env.SUPABASE_DB_URL;
  if (!connectionString) return false;

  const { Client } = require('pg');
  const client = new Client({
    connectionString,
    ssl: { rejectUnauthorized: false },
    connectionTimeoutMillis: 15000,
  });
  const { sql, tableCount } = buildSupabaseSchemaSql(db);
  await client.connect();
  try {
    await client.query(sql);
  } finally {
    await client.end().catch(() => {});
  }
  logger.info(`Supabase schema applied (${tableCount} tables)`);
  return true;
}

module.exports = { buildSupabaseSchemaSql, applySupabaseSchema };
